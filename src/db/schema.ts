import { pgTable, uuid, text, timestamp, boolean, index, uniqueIndex, integer, jsonb } from "drizzle-orm/pg-core";
import { sql } from "drizzle-orm";

/**
 * Two kinds of table live here.
 *
 * PLATFORM tables are shared across every site: who people are, their
 * sessions, and which sites they belong to. They carry no site_id and no
 * row-level security, because they are what we consult *before* a site is
 * known. The app role may read and write them; the integration tests pin
 * the exact list (see PLATFORM_TABLES in tests/integration/tenancy.test.ts).
 *
 * CLIENT tables belong to one site. Every one of them has site_id and is
 * locked by row-level security to the current site. `sites` is the one
 * client table whose policy compares its own id.
 */

// ───────────────────────── client tables ─────────────────────────

/** The tenant. */
export const sites = pgTable("sites", {
  id: uuid("id").primaryKey().defaultRandom(),
  slug: text("slug").notNull().unique(),
  name: text("name").notNull(),
  /** How the storefront looks: see themeSchema in modules/sites/theme.ts. Validated on every write. */
  theme: jsonb("theme").notNull().$type<Record<string, unknown>>().default({}),
  /** Search engines: see searchSettingsSchema in modules/sites/search.ts. */
  search: jsonb("search").notNull().$type<Record<string, unknown>>().default({}),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export type Site = typeof sites.$inferSelect;

// ──────────────────────── platform tables ────────────────────────
// users / sessions / accounts / verifications are the shape Better Auth
// expects (generated by its CLI, pluralised, snake_case). Do not rename
// columns without checking the adapter still maps them.

export const users = pgTable("users", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").default(false).notNull(),
  image: text("image"),
  createdAt: timestamp("created_at").defaultNow().notNull(),
  updatedAt: timestamp("updated_at")
    .defaultNow()
    .$onUpdate(() => new Date())
    .notNull(),
});

export type User = typeof users.$inferSelect;

export const sessions = pgTable(
  "sessions",
  {
    id: text("id").primaryKey(),
    expiresAt: timestamp("expires_at").notNull(),
    token: text("token").notNull().unique(),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .$onUpdate(() => new Date())
      .notNull(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
  },
  (table) => [index("sessions_user_id_idx").on(table.userId)],
);

export const accounts = pgTable(
  "accounts",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestamp("access_token_expires_at"),
    refreshTokenExpiresAt: timestamp("refresh_token_expires_at"),
    scope: text("scope"),
    password: text("password"),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [index("accounts_user_id_idx").on(table.userId)],
);

export const verifications = pgTable(
  "verifications",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: timestamp("expires_at").notNull(),
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .defaultNow()
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [index("verifications_identifier_idx").on(table.identifier)],
);

/** Which sites a person belongs to, and as what. One account, many sites. */
export const MEMBERSHIP_ROLES = ["owner", "staff"] as const;
export type MembershipRole = (typeof MEMBERSHIP_ROLES)[number];

export const memberships = pgTable(
  "memberships",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    role: text("role", { enum: MEMBERSHIP_ROLES }).notNull().default("staff"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("memberships_user_site_idx").on(table.userId, table.siteId),
    index("memberships_site_id_idx").on(table.siteId),
  ],
);

export type Membership = typeof memberships.$inferSelect;

// ───────────────────────── client tables (cont.) ─────────────────────────

/**
 * A page is a stack of sections. Clients edit every word and image,
 * add, remove and reorder sections, and can't break the layout.
 * Soft delete only: deleted_at is set, rows are never removed.
 */
/** draft: only the team. published: live. scheduled: live from published_at on, without anyone touching it. */
export const PAGE_STATUSES = ["draft", "published", "scheduled"] as const;
export type PageStatus = (typeof PAGE_STATUSES)[number];

export const pages = pgTable(
  "pages",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    /** URL path segment. "home" is the site's front page. */
    slug: text("slug").notNull(),
    title: text("title").notNull(),
    status: text("status", { enum: PAGE_STATUSES }).notNull().default("draft"),
    position: integer("position").notNull().default(0),
    /** Search and sharing: see seoSchema in modules/pages/seo.ts. */
    seo: jsonb("seo").notNull().$type<Record<string, unknown>>().default({}),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    publishedAt: timestamp("published_at", { withTimezone: true }),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [
    // Live pages only: a deleted page must not keep its address forever.
    uniqueIndex("pages_site_slug_idx").on(t.siteId, t.slug).where(sql`${t.deletedAt} is null`),
    index("pages_site_id_idx").on(t.siteId),
  ],
);

export type Page = typeof pages.$inferSelect;

/**
 * One block on a page. `type` names an entry in the section registry
 * (src/modules/pages/registry.ts) and `data` is validated against that
 * entry's schema on every write.
 */
export const sections = pgTable(
  "sections",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    pageId: uuid("page_id")
      .notNull()
      .references(() => pages.id, { onDelete: "cascade" }),
    type: text("type").notNull(),
    position: integer("position").notNull().default(0),
    data: jsonb("data").notNull().$type<Record<string, unknown>>().default({}),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [index("sections_page_id_idx").on(t.pageId), index("sections_site_id_idx").on(t.siteId)],
);

export type Section = typeof sections.$inferSelect;

/**
 * An image in a site's media library. The bytes live in object storage
 * under `key` (always `<site_id>/<id>.<ext>`, so one bucket serves every
 * site and no key can be guessed across sites); this row is what the app
 * knows about it. Soft delete only.
 */
export const media = pgTable(
  "media",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    /** Object key in the bucket. The public address is `${R2_PUBLIC_URL}/${key}`. */
    key: text("key").notNull().unique(),
    /** The name the file had when it was uploaded, for the library listing. */
    filename: text("filename").notNull(),
    contentType: text("content_type").notNull(),
    sizeBytes: integer("size_bytes").notNull(),
    width: integer("width").notNull(),
    height: integer("height").notNull(),
    /** Shown to people who can't see the image. Asked for as "Describe this photo". */
    alt: text("alt").notNull().default(""),
    createdBy: text("created_by"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [index("media_site_id_idx").on(t.siteId)],
);

export type Media = typeof media.$inferSelect;

/**
 * A form a client builds: its fields live in `fields` (validated against
 * fieldSchema in modules/forms/fields.ts on every write). A page shows it
 * through a "form" section that points at its id. Soft delete only.
 */
export const forms = pgTable(
  "forms",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    /** Only the team sees this name: "Commission enquiry". */
    name: text("name").notNull(),
    /** Order in the Forms list; the team drags them. */
    position: integer("position").notNull().default(0),
    fields: jsonb("fields").notNull().$type<unknown[]>().default([]),
    buttonText: text("button_text").notNull().default("Send"),
    /** Shown on the page once it's sent. */
    afterMessage: text("after_message").notNull().default("Thanks, we have it. We'll be in touch."),
    /** Who gets an email per submission, comma separated. Empty: the owners. */
    notifyEmails: text("notify_emails").notNull().default(""),
    /** Whether a submission with an email address makes (or updates) a contact. Off for a newsletter signup. */
    createContact: boolean("create_contact").notNull().default(true),
    /** An email back to the sender the moment they send it. Subject and message take {fill-ins}. */
    autoReply: boolean("auto_reply").notNull().default(false),
    replySubject: text("reply_subject").notNull().default(""),
    replyMessage: text("reply_message").notNull().default(""),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [index("forms_site_id_idx").on(t.siteId)],
);

export type Form = typeof forms.$inferSelect;

/** What someone sent through a form, exactly as it arrived. Never edited; marked done, never deleted. */
export const SUBMISSION_STATUSES = ["new", "done"] as const;
export type SubmissionStatus = (typeof SUBMISSION_STATUSES)[number];

export const submissions = pgTable(
  "submissions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    formId: uuid("form_id")
      .notNull()
      .references(() => forms.id, { onDelete: "cascade" }),
    /** Answers by field id. The form's fields at the time are copied in so the inbox can still label them. */
    answers: jsonb("answers").notNull().$type<Record<string, string>>().default({}),
    fields: jsonb("fields").notNull().$type<unknown[]>().default([]),
    status: text("status", { enum: SUBMISSION_STATUSES }).notNull().default("new"),
    /** The contact this made or matched, when the form makes contacts and an email came through. */
    contactId: uuid("contact_id"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    doneAt: timestamp("done_at", { withTimezone: true }),
  },
  (t) => [index("submissions_site_id_idx").on(t.siteId), index("submissions_form_id_idx").on(t.formId)],
);

export type Submission = typeof submissions.$inferSelect;

/**
 * A person who has written to the site. Made from a submission that
 * carried an email address (one contact per address per site), or added
 * by hand. Notes are the team's own, newest last. Soft delete only.
 */
export const contacts = pgTable(
  "contacts",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    name: text("name").notNull().default(""),
    /** Lower-cased. Empty for someone added without one. */
    email: text("email").notNull().default(""),
    phone: text("phone").notNull().default(""),
    notes: jsonb("notes").notNull().$type<{ at: string; text: string }[]>().default([]),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [
    index("contacts_site_id_idx").on(t.siteId),
    // One live contact per address per site; the empty address is many people.
    uniqueIndex("contacts_site_email_idx").on(t.siteId, t.email).where(sql`${t.deletedAt} is null and ${t.email} <> ''`),
  ],
);

export type Contact = typeof contacts.$inferSelect;

/**
 * An article: a dated piece of writing with a cover, listed on the
 * storefront's journal at /journal and read at /journal/<slug>. The body
 * is plain paragraphs (a blank line between them), like a text section.
 * Soft delete only.
 */
export const articles = pgTable(
  "articles",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    slug: text("slug").notNull(),
    title: text("title").notNull(),
    excerpt: text("excerpt").notNull().default(""),
    body: text("body").notNull().default(""),
    /** An imageRef from the library, or null. */
    cover: jsonb("cover").$type<Record<string, unknown> | null>(),
    /** Shows under the title. Empty means the site's name. */
    author: text("author").notNull().default(""),
    status: text("status", { enum: PAGE_STATUSES }).notNull().default("draft"),
    /** Search and sharing: see seoSchema in modules/pages/seo.ts. */
    seo: jsonb("seo").notNull().$type<Record<string, unknown>>().default({}),
    /** The main category: sets the address. Null means /journal/<slug>. */
    categoryId: uuid("category_id"),
    /** Other categories it also appears under. */
    categoryIds: jsonb("category_ids").notNull().$type<string[]>().default([]),
    /** The date shown on it and used to order the journal. Set when first published; editable. */
    publishedAt: timestamp("published_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
  },
  (t) => [
    uniqueIndex("articles_site_slug_idx").on(t.siteId, t.slug).where(sql`${t.deletedAt} is null`),
    index("articles_site_id_idx").on(t.siteId),
  ],
);

export type Article = typeof articles.$inferSelect;

/**
 * Redirects: an old address pointed somewhere useful. Made by hand under
 * Settings · Redirects, or automatically when a live page or article is
 * renamed. `to` is a path on this site or a full address elsewhere.
 */
export const redirects = pgTable(
  "redirects",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    siteId: uuid("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    /** Normalised: leading slash, no trailing slash, lower-case. */
    fromPath: text("from_path").notNull(),
    toPath: text("to_path").notNull(),
    source: text("source", { enum: ["manual", "auto"] }).notNull().default("manual"),
    hits: integer("hits").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("redirects_site_from_idx").on(t.siteId, t.fromPath), index("redirects_site_id_idx").on(t.siteId)],
);
export type Redirect = typeof redirects.$inferSelect;

